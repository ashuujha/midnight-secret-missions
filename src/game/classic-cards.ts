export type DeckArt = Record<number, string>;
let catalog: Promise<DeckArt> | undefined;
/** Fetch the entire public catalog once. Never request an image based on a private hand. */
export function loadDeckArt(): Promise<DeckArt> {
  return (catalog ??= fetch("/deck-art.json")
    .then(async (response) => {
      if (!response.ok) throw new Error("Artwork download failed");
      const data: unknown = await response.json();
      if (
        !data ||
        typeof data !== "object" ||
        Object.keys(data).length !== 52 ||
        DECK.some(
          (c) =>
            typeof (data as DeckArt)[c.id] !== "string" ||
            !/^data:image\/(png|jpeg|webp|gif);base64,/.test(
              (data as DeckArt)[c.id],
            ),
        )
      )
        throw new Error("Invalid artwork catalog");
      return data as DeckArt;
    })
    .catch((error) => {
      catalog = undefined;
      throw error;
    }));
}
